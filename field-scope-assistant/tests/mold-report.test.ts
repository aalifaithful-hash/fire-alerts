import { beforeEach, describe, expect, it } from "vitest";
import { mkdtempSync, readFileSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { NextRequest } from "next/server";
import { rulesAnalyze } from "@/lib/report/rules";
import { analyzeReport } from "@/lib/report/analyzer";
import { proposeChanges, stillMissing } from "@/lib/report/match";
import { RoomScanData } from "@/lib/scan";

/**
 * Mold report upload → rules analysis → scope matching. Reference case: Test 1
 * (308 E 72nd St, Unit 4D, Carol Vinelli, mold under wood flooring). Fixtures are SAMPLE reports
 * generated by scripts/make-sample-mold-reports.mjs (fictional).
 */
process.env.DATABASE_URL = "pglite://memory";
delete process.env.POSTGRES_URL;
delete process.env.APP_PASSCODE;
delete process.env.AI_PROVIDER;
process.env.DATA_DIR = mkdtempSync(path.join(os.tmpdir(), "fsa-report-"));

const { resetLocalDbForTests } = await import("@/lib/db");
const repo = await import("@/lib/repo");
const scans = await import("@/lib/scans");
const { extractPageTexts } = await import("@/lib/pdf");
const { quickStart } = await import("@/lib/quickstart");
const { ingestReport, reportView, applyReport, confirmReport } = await import("@/lib/report/service");
const docsRoute = await import("@/app/api/projects/[pid]/documents/route");

const A = new Uint8Array(readFileSync("tests/fixtures/sample-mold-report-308-E-72nd-St-4D.pdf"));
const B = new Uint8Array(readFileSync("tests/fixtures/sample-mold-report-429-E-52nd-St-5C.pdf"));
const TEST1 = { address: "308 E 72nd St, New York, NY 10021", unit: "4D", customer: "Carol Vinelli", job: "mold" as const, appointmentTime: "11:00", notes: "Mold under wood flooring. Has Mold report she will send over." };

beforeEach(() => resetLocalDbForTests());

describe("rules analyzer — sample report (a), Test 1", () => {
  it("reads every stated field, with its quote", async () => {
    const f = rulesAnalyze(await extractPageTexts(A));
    expect(f.readable).toBe(true);
    expect(f.address?.value).toBe("308 E 72nd St, New York, NY 10021");
    expect(f.unit?.value).toBe("4D");
    expect(f.customer?.value).toBe("Carol Vinelli");
    expect(f.reportDate?.value).toBe("2026-11-02");
    expect(f.room?.value).toBe("Bedroom");
    expect(f.dims?.value).toEqual({ lengthFt: 12, widthFt: 8, heightFt: 8 });
    expect(f.dims?.quote).toBe("Room dimensions: 12 ft x 8 ft, ceiling height 8 ft");
    expect(f.affectedAreaSF?.value).toBe(96);
    expect(f.floorCoverage?.value).toEqual({ whole: true, pct: 100 });
    expect(f.floorCoverage?.quote).toMatch(/across the entire bedroom floor/);
    expect(f.containment?.value).toEqual({ level: "full", negativeAir: true });
    expect(f.removalExtent?.value).toMatch(/remove all wood flooring and underlayment .* 2 ft beyond visible growth/);
    expect(f.subfloor?.value).toBe("clean");
    expect(f.wallsGrowth?.value).toEqual({ growth: false, walls: [] });
    expect(f.baseboardBacksGrowth?.value).toEqual({ growth: true, walls: ["N", "E"] });
    expect(f.framingGrowth?.value).toBe(false);
    expect(f.moistureSource?.value).toMatch(/radiator supply valve/);
    expect(f.sourceFixed?.value).toBe(true);
    expect(f.moldType?.value).toMatch(/Cladosporium/);
    expect(f.condition?.value).toBe("Condition 3 (actual growth)");
    expect(f.dims?.page).toBe(1);
    expect(f.containment?.page).toBe(2);
  });

  it("leaves unanswered items missing — clearance (stated TBD), year built, flooring run", async () => {
    const f = rulesAnalyze(await extractPageTexts(A));
    expect([f.clearanceCriteria, f.clearanceBy, f.yearBuilt, f.flooringContinuous]).toEqual([null, null, null, null]);
    expect(f.unanswered.map((u) => u.key).sort()).toEqual(["clearanceBy", "clearanceCriteria", "flooringContinuous", "yearBuilt"]);
    expect(f.unanswered.find((u) => u.key === "clearanceCriteria")?.quote).toBe("Post-remediation verification: to be determined.");
  });
});

describe("rules analyzer — phrasing variants", () => {
  const one = (t: string) => rulesAnalyze([t]);
  it("whole floor vs part of it", () => {
    expect(one("Mold growth observed throughout the entire kitchen floor.").floorCoverage?.value).toEqual({ whole: true, pct: 100 });
    expect(one("Visible growth on a portion of the living room floor near the window.").floorCoverage?.value).toEqual({ whole: false, pct: null });
    expect(one("Growth observed on approximately 30% of the bedroom floor.").floorCoverage?.value).toEqual({ whole: false, pct: 30 });
  });
  it("subfloor cleaned vs removed", () => {
    expect(one("Subfloor: remove and replace the plywood subfloor in the affected area.").subfloor?.value).toBe("remove");
    expect(one("Subfloor: HEPA vacuum and wire-brush; do not remove.").subfloor?.value).toBe("clean");
    expect(one("Walls: no growth observed.").subfloor).toBeNull();
  });
  it("clearance criteria and who; source not fixed; year built; flooring run", () => {
    const f = one(
      [
        "Post-remediation verification: performed by an independent licensed mold assessor; visual inspection and air samples comparable to outdoor.",
        "Moisture source: roof leak, not yet repaired.",
        "The building was built in 1931.",
        "The wood flooring continues into the hallway and living room.",
      ].join("\n"),
    );
    expect(f.clearanceBy?.value).toBe("independent licensed mold assessor");
    expect(f.clearanceCriteria?.value).toMatch(/visual inspection and air samples/);
    expect(f.sourceFixed?.value).toBe(false);
    expect(f.yearBuilt?.value).toBe(1931);
    expect(f.flooringContinuous?.value).toEqual({ continues: true, rooms: ["Hallway", "Living room"] });
    expect(one("Flooring stops at the threshold; natural break at the bedroom door.").flooringContinuous?.value).toEqual({ continues: false, rooms: [] });
  });
  it("nothing stated → every scope item is listed as missing, nothing guessed", () => {
    const f = one("Mold Assessment Report\nThis page intentionally left blank.");
    expect(f.dims).toBeNull();
    expect(f.subfloor).toBeNull();
    expect(f.unanswered.length).toBeGreaterThanOrEqual(15);
    expect(stillMissing(f, { yearBuiltKnown: false, runKnown: false })[0]).toMatch(/Affected area and extent/);
  });
  it("a photo of a report (no selectable text) is unreadable — AI path not enabled", async () => {
    const f = await analyzeReport({ pages: [], contentType: "image/jpeg" });
    expect(f.readable).toBe(false);
  });
});

describe("scope matching (pure)", () => {
  it("proposes changes from the report; conflicts with what the PM entered are flagged and off", async () => {
    const f = rulesAnalyze(await extractPageTexts(A));
    const scan = RoomScanData.parse({ loss: { type: "mold" }, materials: { flooring: { type: "wood", affected: true, affectedPct: 50 } }, measurements: { lengthFt: 12, widthFt: 10, heightFt: 8 } });
    const { changes, mismatches } = proposeChanges(f, { roomLabel: "Unit 4D — Kitchen", roomName: "Kitchen", scan, yearBuilt: null });
    const c = (k: string) => changes.find((x) => x.key === k)!;
    expect(c("room.name")).toMatchObject({ proposed: "Bedroom", conflict: true });
    expect(c("measurements")).toMatchObject({ current: "12 × 10 ft, 8 ft ceiling", conflict: true });
    expect(c("floor.pct")).toMatchObject({ current: "50%", proposed: "100% (whole floor)", conflict: true });
    expect(c("subfloor")).toMatchObject({ conflict: false });
    expect(mismatches).toEqual(
      expect.arrayContaining([
        expect.stringMatching(/Different room: the report is for the Bedroom; this scan is "Kitchen"/),
        expect.stringMatching(/Different area: you entered 12 × 10 ft; the report says 12 × 8 ft/),
        expect.stringMatching(/Different extent: you entered 50% of the floor; the report says the whole floor/),
      ]),
    );
  });
});

describe("report upload, wrong report, apply → scope (Test 1)", () => {
  it("(b) 429 E 52nd St report on the Test 1 project → Wrong report?, held until confirmed or cancelled", async () => {
    const q = await quickStart(TEST1);
    const d = await ingestReport(q.projectId, { name: "sample-mold-report-429-E-52nd-St-5C.pdf", bytes: B });
    expect(d.status).toBe("needs_confirmation");
    expect(d.wrongReport).toMatch(/^Wrong report\? This report states address "429 E 52nd St, New York, NY 10022" and name "Jane Example", but this project is 308 E 72nd St/);
    const v = await reportView(q.projectId, q.visitId);
    expect(v.active).toBeNull(); // nothing analyzed into the scope until confirmed
    expect(v.reports[0]).toMatchObject({ status: "needs_confirmation" });
    await expect(applyReport(q.projectId, q.visitId, d.id, [])).rejects.toThrow(/Confirm the report/);
    const c = await confirmReport(q.projectId, d.id);
    expect([c.status, c.confirmed]).toEqual(["ready", true]);
  });

  it("(a) matching report: findings, proposed lines with math + report justification, pending cleared vs still missing", async () => {
    const q = await quickStart(TEST1);
    const d = await ingestReport(q.projectId, { name: "sample-mold-report-308-E-72nd-St-4D.pdf", bytes: A });
    expect([d.status, d.wrongReport]).toEqual(["ready", null]);
    const v = (await reportView(q.projectId, q.visitId)).active!;
    expect(v.applied).toBe(false);
    expect(v.findings.find((r) => r.key === "floorCoverage")).toMatchObject({ value: "Whole floor", stated: "found", page: 1 });
    expect(v.findings.find((r) => r.key === "clearanceCriteria")).toMatchObject({ value: null, stated: "open", quote: "Post-remediation verification: to be determined." });
    expect(v.findings.find((r) => r.key === "yearBuilt")).toMatchObject({ stated: "missing" });
    expect(v.mismatches).toEqual([]);
    expect(v.changes.map((c) => c.key).sort()).toEqual(["floor.pct", "measurements", "room.name", "source.fixture", "source.status", "subfloor"]);
    expect(v.changes.every((c) => !c.conflict)).toBe(true);
    const p = (id: string) => v.preview.find((l) => l.id === id)!;
    expect(p("mold.floor.remove")).toMatchObject({ quantity: 96, unit: "SF", calc: "12 ft × 8 ft = 96 SF" });
    expect(p("mold.floor.remove").justification).toMatch(/Report states growth across the full 12 × 8 ft bedroom floor \(96 SF\): “Visible mold growth was observed/);
    expect(p("mold.containment")).toMatchObject({ quantity: 320, unit: "SF" }); // 40 LF × 8 ft
    expect(p("baseboard")).toMatchObject({ quantity: 40, unit: "LF" });
    expect(p("baseboard").justification).toMatch(/growth observed on the back of the baseboard .* discard/);
    expect(p("walls.paint")).toMatchObject({ quantity: 320, unit: "SF" });
    expect(p("mold.subfloor.clean").justification).toMatch(/clean and treat the subfloor \(do not remove\)/);
    expect(v.preview.find((l) => l.id === "mold.subfloor.remove")).toBeUndefined();
    expect(v.preview.every((l) => l.status === "suggested")).toBe(true);
    expect(v.stillMissing).toEqual([
      "Clearance criteria and who performs the post-remediation verification (report: “Post-remediation verification: to be determined.”)",
      "Year built — not in the report (lead/asbestos check before demolition)",
      "Whether the wood flooring runs into other rooms — not in the report",
    ]);

    // apply → room renamed, scan updated, lines suggested; the scope's pending items now list only what is still missing
    const after = (await applyReport(q.projectId, q.visitId, d.id, v.changes.filter((c) => !c.conflict).map((c) => c.key))).active!;
    expect(after.applied).toBe(true);
    expect(after.changes).toEqual([]);
    const view = await scans.getVisitScans(q.projectId, q.visitId);
    const room = view.rooms[0];
    expect(room.label).toBe("Unit 4D — Bedroom");
    expect(room.data.measurements).toMatchObject({ lengthFt: 12, widthFt: 8, heightFt: 8 });
    expect(room.data.loss.assessmentReport).toBe("received");
    expect(room.data.lines.find((l) => l.id === "mold.floor.remove")).toMatchObject({ quantity: 96, status: "suggested" });
    expect(room.data.lines.flatMap((l) => l.flags)).not.toContain("Confirm against the mold assessment report (pending).");
    const qs = room.analysis.questions.join(" ");
    expect(qs).not.toMatch(/measure length|whole floor or part|moisture source caused/);
    expect(room.analysis.pending.join("\n")).not.toMatch(/Affected area and extent|Containment level/);
    expect(room.analysis.pending).toHaveLength(3);
    const visit = await repo.getVisit(q.projectId, q.visitId);
    expect(visit.text).toMatch(/Pending the mold assessment report: STILL MISSING after the mold report: Clearance criteria/);
    expect(visit.text).not.toMatch(/Pending the mold assessment report: Affected area and extent/);

    // accept with the existing pattern → it prints in the scope with the report quantity
    await scans.decideLines(q.projectId, q.visitId, room.locationId, ["mold.floor.remove", "mold.containment"], "accept");
    const v2 = await repo.getVisit(q.projectId, q.visitId);
    expect(v2.text).toMatch(/Remove & bag wood flooring with growth — 96 SF/);
    expect(v2.text).toMatch(/Set up containment .* — 320 SF/);
  });

  it("mismatches with the manually entered scope are warned and never silently overwritten", async () => {
    const q = await quickStart(TEST1);
    const view0 = await scans.getVisitScans(q.projectId, q.visitId);
    const loc = view0.rooms[0].locationId;
    const { lines: _l, decisions: _d, ...data } = view0.rooms[0].data;
    void _l;
    void _d;
    await scans.saveRoomScan(q.projectId, q.visitId, loc, { ...data, materials: { ...data.materials, flooring: { ...data.materials.flooring, affectedPct: 50 } }, measurements: { ...data.measurements, lengthFt: 12, widthFt: 10, heightFt: 8 } });
    const d = await ingestReport(q.projectId, { name: "a.pdf", bytes: A });
    const v = (await reportView(q.projectId, q.visitId)).active!;
    expect(v.mismatches.join(" ")).toMatch(/Different area: you entered 12 × 10 ft; the report says 12 × 8 ft/);
    expect(v.mismatches.join(" ")).toMatch(/Different extent: you entered 50%/);
    // the preview (and a default apply) keeps the PM's numbers: 12 × 10 × 50% = 60 SF
    expect(v.preview.find((l) => l.id === "mold.floor.remove")?.quantity).toBe(60);
    await applyReport(q.projectId, q.visitId, d.id, v.changes.filter((c) => !c.conflict).map((c) => c.key));
    const room = (await scans.getVisitScans(q.projectId, q.visitId)).rooms[0];
    expect(room.data.measurements.widthFt).toBe(10);
    expect(room.data.materials.flooring.affectedPct).toBe(50);
    // the PM can choose the report's numbers explicitly
    await applyReport(q.projectId, q.visitId, d.id, ["measurements", "floor.pct"]);
    const room2 = (await scans.getVisitScans(q.projectId, q.visitId)).rooms[0];
    expect(room2.data.lines.find((l) => l.id === "mold.floor.remove")?.quantity).toBe(96);
  });

  it("a photo of the report is stored (same upload route) and shows the AI-not-enabled state", async () => {
    const q = await quickStart(TEST1);
    const jpg = new Uint8Array([0xff, 0xd8, 0xff, 0xe0, ...new Array(200).fill(0)]);
    const form = new FormData();
    form.append("file", new File([jpg], "report-photo.jpg", { type: "image/jpeg" }));
    form.append("kind", "mold_report");
    const req = new NextRequest(`http://localhost/api/projects/${q.projectId}/documents`, { method: "POST", body: form });
    const res = await (docsRoute.POST as (r: NextRequest, c: { params: Promise<{ pid: string }> }) => Promise<Response>)(req, { params: Promise.resolve({ pid: q.projectId }) });
    const j = (await res.json()) as { document: { status: string; contentType: string; readable: boolean } };
    expect(res.status).toBe(200);
    expect(j.document).toMatchObject({ status: "unreadable", contentType: "image/jpeg", readable: false });
    const v = await reportView(q.projectId, q.visitId);
    expect(v.active).toBeNull();
    expect(v.ai).toEqual({ enabled: false, message: expect.stringMatching(/^AI analysis not enabled/) });
  });
});
